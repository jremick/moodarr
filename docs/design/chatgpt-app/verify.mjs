// Browser-only UX proof. This is not MCP, auth, or live-instance evidence.
export default async function verify(page, outputDirectory) {
  const checks = [];
  const errors = [];
  const networkActions = [];
  page.on('request', request => {
    if (['fetch', 'xhr'].includes(request.resourceType()) || request.method() !== 'GET') networkActions.push(request.url());
  });
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const check = (condition, name) => {
    if (!condition) throw new Error(name);
    checks.push(name);
  };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1360, height: 1000 });
  await page.goto('http://127.0.0.1:4178/');
  await page.getByRole('button', { name: 'View Chef', exact: true }).waitFor();
  await page.locator('img').evaluateAll(images => Promise.all(images.map(image => image.complete ? undefined : new Promise(resolve => {
    image.addEventListener('load', resolve, { once: true });
    image.addEventListener('error', resolve, { once: true });
  }))));
  check(await page.locator('img').evaluateAll(images => images.every(image => image.naturalWidth > 0)), 'All three review posters loaded');
  check(await page.getByRole('button', { name: /^View (Chef|Hunt for|Paddington)/ }).count() === 3, 'Three scannable recommendations');
  await page.screenshot({ path: `${outputDirectory}/desktop.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'View Chef', exact: true }).click();
  await page.getByRole('button', { name: 'More like this', exact: true }).click();
  await page.getByText('Preference saved for this session.', { exact: true }).waitFor();
  checks.push('Feedback produces an acknowledged session state');
  await page.getByRole('button', { name: 'Add to Watchlist', exact: true }).click();
  await page.getByRole('button', { name: 'On your Watchlist', exact: true }).waitFor();
  checks.push('Watchlist action reaches an acknowledged state');
  await page.keyboard.press('Escape');
  check(await page.getByRole('button', { name: 'View Chef', exact: true }).evaluate(el => el === document.activeElement), 'Dialog restores keyboard focus');
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  await page.getByRole('button', { name: 'Preview request', exact: true }).click();
  check(await page.getByRole('button', { name: 'Confirm request', exact: true }).isDisabled(), 'Request disabled before explicit confirmation');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  check(await page.getByRole('button', { name: 'Preview request', exact: true }).isVisible(), 'Cancel returns without requesting');
  await page.keyboard.press('Escape');
  await page.getByLabel('Review scenario').selectOption('uncertain');
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  await page.getByRole('button', { name: 'Preview request', exact: true }).click();
  await page.getByLabel('Request Paddington 2 (2017) for my account.').check();
  await page.getByRole('button', { name: 'Confirm request', exact: true }).dblclick();
  await page.getByRole('heading', { name: 'We could not confirm the outcome.' }).waitFor();
  check(await page.getByRole('button', { name: 'Confirm request', exact: true }).count() === 0, 'Uncertain outcome cannot blindly resend');
  await page.screenshot({ path: `${outputDirectory}/uncertain.png`, fullPage: false, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  check(await page.getByRole('heading', { name: 'We could not confirm the outcome.' }).isVisible(), 'Closing and reopening retains the unresolved request');
  for (let index = 0; index < 6; index++) {
    await page.keyboard.press('Tab');
    check(await page.locator('#title-dialog').evaluate(element => document.activeElement === document.body || element.contains(document.activeElement)), `Modal blocks background controls after Tab ${index + 1}`);
  }
  await page.getByRole('button', { name: 'Check request status', exact: true }).click();
  await page.getByRole('heading', { name: 'Request received' }).waitFor();
  check(await page.getByText('Request reference DEMO-001', { exact: true }).isVisible(), 'Readback resolves the original request reference');
  await page.keyboard.press('Escape');
  await page.getByLabel('Review scenario').selectOption('readonly');
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  check(await page.getByRole('button', { name: 'Preview request', exact: true }).count() === 0, 'Read-only account has no request control');
  await page.keyboard.press('Escape');
  await page.getByLabel('Review scenario').selectOption('expired');
  check(await page.getByRole('button', { name: 'Reconnect Moodarr', exact: true }).isVisible(), 'Expired session offers reconnection');
  check(await page.getByRole('button', { name: /^View / }).count() === 0, 'Expired session hides personal catalog');
  await page.getByRole('button', { name: 'Reconnect Moodarr', exact: true }).click();
  await page.getByLabel('Moodarr address').fill('http://192.168.1.20:5055');
  await page.getByRole('button', { name: 'Check connection', exact: true }).click();
  await page.getByRole('heading', { name: 'This address is on a private network.' }).waitFor();
  check(await page.getByRole('button', { name: 'Continue to sign in', exact: true }).count() === 0, 'LAN-only URL cannot advance to sign-in');
  await page.getByLabel('Moodarr address').fill('https://cinema.example.com');
  await page.getByRole('button', { name: 'Check connection', exact: true }).click();
  await page.getByRole('button', { name: 'Continue to sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Authorize connection', exact: true }).click();
  await page.getByRole('heading', { name: 'Your movie nights, connected.' }).waitFor();
  checks.push('Connection includes a separate consent step');
  await page.screenshot({ path: `${outputDirectory}/connected.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Return to preview', exact: true }).click();
  await page.getByLabel('Review scenario').selectOption('ready');
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  await page.getByRole('button', { name: 'Preview request', exact: true }).click();
  await page.getByLabel('Request Paddington 2 (2017) for my account.').check();
  await page.getByRole('button', { name: 'Confirm request', exact: true }).click();
  await page.getByRole('heading', { name: 'Request received' }).waitFor();
  checks.push('Successful request remains distinct from ready-to-watch availability');
  await page.keyboard.press('Escape');
  await page.getByLabel('Review scenario').selectOption('unreachable');
  await page.getByRole('button', { name: 'Check connection', exact: true }).click();
  await page.getByRole('heading', { name: 'We could not reach this endpoint.' }).waitFor();
  check(await page.getByRole('button', { name: 'Continue to sign in', exact: true }).count() === 0, 'Unreachable endpoint cannot proceed');
  await page.getByLabel('Review scenario').selectOption('auth');
  await page.getByRole('button', { name: 'Check connection', exact: true }).click();
  await page.getByRole('heading', { name: 'Supported authentication was not found.' }).waitFor();
  check(await page.getByRole('button', { name: 'Continue to sign in', exact: true }).count() === 0, 'Unsupported authentication cannot proceed');
  await page.getByLabel('Review scenario').selectOption('ready');
  await page.getByRole('button', { name: 'Connect an instance', exact: true }).click();
  await page.screenshot({ path: `${outputDirectory}/connection.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'In conversation', exact: true }).click();
  await page.getByLabel('Review scenario').selectOption('empty');
  check(await page.getByRole('heading', { name: 'No titles fit all of these filters.' }).isVisible(), 'Empty results provide a clear next step');
  await page.getByRole('button', { name: 'Show sample picks', exact: true }).click();
  await page.getByRole('button', { name: 'Dark appearance', exact: true }).click();
  await page.screenshot({ path: `${outputDirectory}/dark.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Light appearance', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile has no horizontal page overflow');
  await page.screenshot({ path: `${outputDirectory}/mobile.png`, fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'View Paddington 2', exact: true }).click();
  check(await page.getByRole('button', { name: 'Preview request', exact: true }).isVisible(), 'Mobile title action remains available');
  await page.getByRole('button', { name: 'Preview request', exact: true }).click();
  await page.screenshot({ path: `${outputDirectory}/mobile-confirmation.png`, fullPage: false, animations: 'disabled' });
  check(networkActions.length === 0, 'No API, form, or mutation network requests');
  check(errors.length === 0, `No browser script errors: ${errors.join(', ')}`);
  return { layer: 'fixture UX only', checks, screenshots: ['desktop', 'uncertain', 'connected', 'connection', 'dark', 'mobile', 'mobile-confirmation'], errors };
}
