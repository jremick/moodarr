import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
import { log } from 'node:console';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, URL } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const html = await readFile(resolve(root, 'dist/index.html'), 'utf8');
if (/<script\b[^>]*\bsrc\s*=/i.test(html) || /<link\b[^>]*\brel\s*=\s*["']stylesheet["']/i.test(html)) {
  throw new Error('The MCP UI must contain its scripts and styles in one HTML resource.');
}
const sha256 = createHash('sha256').update(html).digest('hex');
const uri = `ui://moodarr/${sha256}/app.html`;
const mimeType = 'text/html;profile=mcp-app';
const description = 'Moodarr search results, title details, and explicit request confirmation.';
const resourceMeta = { ui: { prefersBorder: true, csp: { connectDomains: [], resourceDomains: [], frameDomains: [] } } };
const renderTools = ['moodarr_search', 'moodarr_get_item', 'moodarr_preview_request'];
const appTools = [...renderTools, 'moodarr_library_stats', 'moodarr_record_feedback', 'moodarr_create_request', 'moodarr_add_to_watchlist'];
const toolMeta = Object.fromEntries(appTools.map((name) => [name, {
  ui: { ...(renderTools.includes(name) ? { resourceUri: uri } : {}), visibility: ['model', 'app'] },
}]));
const manifest = { schemaVersion: 1, name: 'moodarr-chatgpt-ui', uri, mimeType, description,
  sha256, bytes: Buffer.byteLength(html), resourceMeta, toolMeta };
const resource = { uri, mimeType, text: html, _meta: resourceMeta };

await writeFile(resolve(root, 'dist/manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(resolve(root, 'dist/resource.mjs'), `// Generated by npm run build. Do not edit.\n`
  + `export const manifest = ${JSON.stringify(manifest)};\n`
  + `export const moodarrUiToolMeta = manifest.toolMeta;\n`
  + `export const moodarrUiResource = ${JSON.stringify(resource)};\n`
  + `export function registerMoodarrUiResource(server) {\n`
  + `  return server.registerResource(manifest.name, manifest.uri, {\n`
  + `    mimeType: manifest.mimeType, description: manifest.description, _meta: manifest.resourceMeta,\n`
  + `  }, async () => ({ contents: [moodarrUiResource] }));\n}\n`);
await writeFile(resolve(root, 'dist/resource.d.mts'), `import type { McpServer } from '@modelcontextprotocol/server';\n`
  + `export declare const manifest: { schemaVersion: number; name: string; uri: string; mimeType: string; description: string; sha256: string; bytes: number; resourceMeta: Record<string, unknown>; toolMeta: Record<string, { ui: { resourceUri?: string; visibility: ('model' | 'app')[] } }> };\n`
  + `export declare const moodarrUiToolMeta: typeof manifest.toolMeta;\n`
  + `export declare const moodarrUiResource: { uri: string; mimeType: string; text: string; _meta: Record<string, unknown> };\n`
  + `export declare function registerMoodarrUiResource(server: Pick<McpServer, 'registerResource'>): ReturnType<McpServer['registerResource']>;\n`);
log(`Built MCP UI resource: ${manifest.bytes} bytes; sha256 ${sha256}`);
